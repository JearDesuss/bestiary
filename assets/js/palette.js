// Every palette gets a flat list too, for the glitch bars and the backdrop,
// which are allowed to reach for anything in the work.
for (const p of P) {
  p.all = [...new Set([
    ...p.field, p.sky, ...p.leaf, ...p.flesh, ...p.metal, ...p.wool,
    ...p.cloth, ...p.fur, p.horn, p.beak, p.gold, ...p.wing,
  ])]
}

export const PALETTES = P

export function pickPalette(rng) {
  return rng.pick(P)
}

export function paletteById(id) {
  return P.find((p) => p.id === id) ?? P[0]
}
